                        }
                    }
                }
           }
           keepDependencies()
           scm {
                git {
                    remote {
                        url(gitUrl)
                        credentials(repoCreds)
                    }
                    branch("*/"+genericBranch)
                }
           }
           label(hostLabel)
           triggers {
                scm("H/5 * * * *")
           }
           steps {
               copyArtifacts('yocto-build') {
                   includePatterns('artifacts/sdk/*')
                   targetDirectory('sdk')
                   flatten()
                   optional()
                   buildSelector {
                       latestSuccessful(true)
                   }
               }
               shell(scriptFile.getText())
           }
      }
}
